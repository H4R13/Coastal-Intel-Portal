/**
 * Load the team's mangrove layers into PostgreSQL (tables in schema.sql) and clear their cached answers.
 *
 *   node server/load-mangroves.mjs ["Other Data/AMSK/Mangrove year layers/Mangrove year layers"]
 *
 * Reads, from that folder:
 *   gmw_pak_<year>.shp                           mapped extent, one file per year
 *   Mangroves for future/<year>_<scenario>.shp   projected extent
 *   gmw_pak_year_summary.csv, Mangroves for future/projections.csv   area per year
 * Everything is stored as delivered; a reload replaces the previous contents.
 */
import fs from "node:fs"; import path from "node:path";
import * as shp from "shapefile";
try { process.loadEnvFile(path.join(process.cwd(), ".env")); } catch { /* settings may come from the environment */ }
const { pool, clearCache, redis } = await import("./db.mjs");
const shapefile = shp.default ?? shp;

const dir = path.resolve(process.argv[2] ?? "Other Data/AMSK/Mangrove year layers/Mangrove year layers");
const future = path.join(dir, "Mangroves for future");
if (!fs.existsSync(dir)) { console.error(`Folder not found: ${dir}`); process.exit(1); }

const csv = (file) => {
  const [head, ...rows] = fs.readFileSync(file, "utf8").trim().split(/\r?\n/).map((l) => l.split(","));
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
};

const INSERT = `
  insert into mangrove_extent (scenario, year, geom)
  select $1::text, $2::int, d.geom
  from unnest($3::text[]) as j
  cross join lateral ST_Subdivide(ST_CollectionExtract(ST_MakeValid(ST_SetSRID(ST_GeomFromGeoJSON(j), 3857)), 3), 256) as piece
  cross join lateral ST_Dump(piece) as d
  where GeometryType(d.geom) = 'POLYGON'`;

async function loadShapes(db, file, scenario, year) {
  const src = await shapefile.open(file);
  if (Math.abs(src.bbox[0]) <= 180) throw new Error(`${path.basename(file)} is not in Web Mercator (EPSG:3857) as expected`);
  let batch = [], pieces = 0;
  const flush = async () => { if (batch.length) { pieces += (await db.query(INSERT, [scenario, year, batch])).rowCount; batch = []; } };
  for (let r = await src.read(); !r.done; r = await src.read()) {
    if (!r.value.geometry) continue;
    batch.push(JSON.stringify(r.value.geometry));
    if (batch.length >= 200) await flush();
  }
  await flush();
  console.log(`  ${scenario.padEnd(9)} ${year}  ${String(pieces).padStart(6)} pieces`);
}

const db = await pool.connect();
try {
  await db.query(fs.readFileSync(new URL("./schema.sql", import.meta.url), "utf8"));
  await db.query("begin");
  await db.query("truncate mangrove_extent, mangrove_area");

  const observed = fs.readdirSync(dir).map((f) => f.match(/^gmw_pak_(\d{4})\.shp$/)).filter(Boolean).sort((a, b) => a[1] - b[1]);
  console.log(`Mapped extent: ${observed.length} years`);
  for (const m of observed) await loadShapes(db, path.join(dir, m[0]), "observed", +m[1]);

  const projected = fs.existsSync(future) ? fs.readdirSync(future).map((f) => f.match(/^(\d{4})_([a-z]+)\.shp$/)).filter(Boolean).sort() : [];
  console.log(`Projected extent: ${projected.length} layers`);
  for (const m of projected) await loadShapes(db, path.join(future, m[0]), m[2], +m[1]);

  const areas = [
    ...csv(path.join(dir, "gmw_pak_year_summary.csv")).map((r) => ["observed", +r.year, +r.area_km2]),
    ...(fs.existsSync(path.join(future, "projections.csv")) ? csv(path.join(future, "projections.csv")).map((r) => [r.scenario, +r.year, +r.area_km2]) : []),
  ];
  for (const a of areas) await db.query("insert into mangrove_area (scenario, year, area_km2) values ($1, $2, $3)", a);
  console.log(`Area table: ${areas.length} rows`);

  // scenario names as the team delivered them in projections.csv (e.g. "Good (SSP1-2.6)")
  const labels = new Map(fs.existsSync(path.join(future, "projections.csv")) ? csv(path.join(future, "projections.csv")).map((r) => [r.scenario, r.label]) : []);
  const info = {
    source: "Global Mangrove Watch yearly extent (gmw_v4112 extracts) supplied by the project team",
    scenarios: [...new Set(projected.map((m) => m[2]))].map((id) => ({ id, label: labels.get(id) ?? id })),
    note: "Projected extents were generated by the team with a Cellular Automata-Markov model.",
  };
  await db.query("insert into layer_info (layer, info) values ('mangroves', $1) on conflict (layer) do update set info = excluded.info, loaded_at = now()", [info]);
  await db.query("commit");
  await db.query("analyze mangrove_extent");
  console.log(`Cleared ${await clearCache("mangroves").catch(() => 0)} cached answers`);
} catch (e) {
  await db.query("rollback").catch(() => {});
  console.error(`Load failed, nothing was changed: ${e.message}`);
  process.exitCode = 1;
} finally {
  db.release(); await pool.end(); redis.disconnect();
}
